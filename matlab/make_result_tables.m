function make_result_tables(esDir, csDir)
%MAKE_RESULT_TABLES Write the headline result tables as LaTeX (booktabs + siunitx).
%   Inputs: reports/evidence-sufficiency/results.json and policies.csv, and
%   reports/claim-sufficiency/results.json. Every number is read from those
%   files and rounded as in the generated matrix.md tables. Outputs are tabular
%   fragments next to their sources:
%     evidence-sufficiency/outcomes-table.tex    artifact outputs and checks
%     evidence-sufficiency/policies-table.tex    comparator decisions, coverage and cost
%     claim-sufficiency/explanations-table.tex   explanation outputs and claim correctness
%     claim-sufficiency/decisions-table.tex      evidence sufficiency per claim
%   Status uses colour plus fill: a blue filled dot passes, an orange open dot fails.

write_outcomes(esDir);
write_policies(esDir);
C = jsondecode(fileread(fullfile(csDir, 'results.json')));
write_explanations(C, csDir);
write_decisions(C, csDir);
end

% ---------------------------------------------------------------------------
function L = preamble(source)
L = [
"% Generated by matlab/make_result_tables.m from " + source + "; do not edit by hand."
"\providecommand{\passmark}{\textcolor[rgb]{0,0.447,0.741}{$\bullet$}}"
"\providecommand{\failmark}{\textcolor[rgb]{0.85,0.325,0.098}{$\circ$}}"
];
end

function s = mark(ok)
if ok, s = "\passmark"; else, s = "\failmark"; end
end

function s = yesno(ok)
if ok, s = "yes~\passmark"; else, s = "no~\failmark"; end
end

% ---------------------------------------------------------------------------
function write_outcomes(esDir)
R = jsondecode(fileread(fullfile(esDir, 'results.json')));
rows = R.rows;
labels = containers.Map( ...
    {'correct_control', 'benign_partition', 'nuisance_density', 'modulus_fault', 'area_fault', 'load_fault'}, ...
    {'Correct control', 'Benign partition', 'Nuisance density', 'Modulus fault', 'Area fault', 'Load fault'});
assert(all(arrayfun(@(r) r.checks.completed, rows)), 'a completion check failed; the note below would be wrong');
L = [preamble("reports/evidence-sufficiency/results.json")
"\begin{tabular}{@{}l S[table-format=3.1]@{\,}c S[table-format=1.4]@{\,}c S[table-format=4.1]@{\,}c l@{}}"
"\toprule"
" & \multicolumn{2}{c}{Stress $\sigma$ (\unit{MPa})} & \multicolumn{2}{c}{Extension $\delta$ (\unit{mm})} & \multicolumn{2}{c}{Reaction $R$ (\unit{N})} & Full tuple \\"
"\midrule"];
loadings = ["force", "displacement"];
for i = 1:numel(loadings)
    sel = rows(arrayfun(@(r) string(r.loading) == loadings(i), rows));
    assert(numel(sel) == 6, 'expected 6 artifacts under %s loading', loadings(i));
    ref = sel(1).reference;
    if i > 1, L(end + 1) = "\addlinespace"; end %#ok<AGROW>
    L(end + 1) = "\multicolumn{8}{@{}l}{\textit{Prescribed " + loadings(i) + "}} \\"; %#ok<AGROW>
    L(end + 1) = sprintf("\\quad\\textit{Specification reference} & %.1f & & %.4f & & %.1f & & \\\\", ...
        ref.stress, ref.displacement, ref.force); %#ok<AGROW>
    for r = sel'
        assert(isequal(r.reference, ref), 'reference differs within %s loading', loadings(i));
        o = r.output;
        tuple = "incorrect";
        if r.correct, tuple = "correct"; end
        L(end + 1) = sprintf("\\quad %s & %.1f & %s & %.4f & %s & %.1f & %s & %s \\\\", ...
            labels(r.variant), o.stress, mark(r.checks.stress), o.displacement, ...
            mark(r.checks.displacement), o.force, mark(r.checks.reaction), tuple); %#ok<AGROW>
    end
end
L = [L
"\bottomrule"
"\multicolumn{8}{@{}l}{\footnotesize \passmark\ check passes against the reference; \failmark\ check fails.} \\"
"\multicolumn{8}{@{}l}{\footnotesize The completion check passes for every artifact.} \\"
"\end{tabular}"];
writelines(L, fullfile(esDir, 'outcomes-table.tex'));
end

% ---------------------------------------------------------------------------
function write_policies(esDir)
opts = detectImportOptions(fullfile(esDir, 'policies.csv'), 'TextType', 'string');
opts = setvartype(opts, 'policy', 'string');
T = readtable(fullfile(esDir, 'policies.csv'), opts);
labels = containers.Map( ...
    {'fixed_stress', 'random', 'sensitivity', 'all_checks', 'cautious_stress', 'abstain'}, ...
    {'Fixed stress', 'Random (exact)', 'Modulus sensitivity', 'All checks', 'Cautious stress', 'Always abstain'});
n = unique(T.artifacts);
assert(isscalar(n), 'policies were scored on different artifact sets');
L = [preamble("reports/evidence-sufficiency/policies.csv")
"\begin{tabular}{@{}l S[table-format=1.0] S[table-format=1.0] S[table-format=2.0] S[table-format=3.1] S[table-format=1.0] S[table-format=2.1]@{}}"
"\toprule"
" & \multicolumn{3}{c}{Decisions (count)} & & & \\"
"\cmidrule(lr){2-4}"
"Policy & {Wrong accepts} & {Wrong rejects} & {Abstentions} & {Coverage (\%)} & {\shortstack{Mean cost\\(tokens/artifact)}} & {\shortstack{Decision\\error (\%)}} \\"
"\midrule"];
for k = 1:height(T)
    % policies with the same coverage and mean cost are compared directly; others are set apart
    if k > 1 && ~(T.coverage(k) == T.coverage(k - 1) && T.mean_cost(k) == T.mean_cost(k - 1))
        L(end + 1) = "\addlinespace"; %#ok<AGROW>
    end
    if isnan(T.error_among_decisions(k))
        err = "{n/a}";
    else
        err = sprintf("%.1f", 100 * T.error_among_decisions(k));
    end
    L(end + 1) = sprintf("%s & %g & %g & %g & %.1f & %g & %s \\\\", labels(char(T.policy(k))), ...
        T.wrong_accepts(k), T.wrong_rejects(k), T.abstentions(k), 100 * T.coverage(k), ...
        T.mean_cost(k), err); %#ok<AGROW>
end
L = [L
"\bottomrule"
sprintf("\\multicolumn{7}{@{}l}{\\footnotesize Each policy is scored on the same %d development artifacts.} \\\\", n)
"\multicolumn{7}{@{}l}{\footnotesize Policies in one group share coverage and mean cost.} \\"
"\end{tabular}"];
writelines(L, fullfile(esDir, 'policies-table.tex'));
end

% ---------------------------------------------------------------------------
function write_explanations(C, csDir)
L = [preamble("reports/claim-sufficiency/results.json")
"\begin{tabular}{@{}l S[table-format=6.0] S[table-format=2.1] S[table-format=1.4] l l@{}}"
"\toprule"
" & & & & \multicolumn{2}{c}{Claim correct} \\"
"\cmidrule(l){5-6}"
"Explanation & {Modulus $E$ (\unit{MPa})} & {Stress $\sigma$ (\unit{MPa})} & {Deflection $\delta$ (\unit{mm})} & Stress & Deflection \\"
"\midrule"];
cases = C.cases;
for i = 1:numel(cases)
    c = cases(i);
    if i > 1, L(end + 1) = "\addlinespace"; end %#ok<AGROW>
    L(end + 1) = sprintf("\\multicolumn{6}{@{}l}{\\textit{Prescribed %s; observed stress \\qty{%g}{MPa}}} \\\\", ...
        c.loading_convention, c.evidence.stress); %#ok<AGROW>
    for a = c.artifacts'
        L(end + 1) = sprintf("\\quad %s & %g & %.1f & %.4f & %s & %s \\\\", a.id, ...
            a.implemented_modulus_MPa, a.output.stress, a.output.displacement, ...
            yesno(a.claim_correctness.stress), yesno(a.claim_correctness.deflection)); %#ok<AGROW>
    end
end
L = [L
"\bottomrule"
"\multicolumn{6}{@{}l}{\footnotesize Only the implemented elastic modulus differs between H1 and H2.} \\"
"\multicolumn{6}{@{}l}{\footnotesize Correctness is checked against the original specification.} \\"
"\end{tabular}"];
writelines(L, fullfile(csDir, 'explanations-table.tex'));
end

% ---------------------------------------------------------------------------
function write_decisions(C, csDir)
L = [preamble("reports/claim-sufficiency/results.json")
"\begin{tabular}{@{}l l l l l@{}}"
"\toprule"
"Claim & Compatible explanations & Evidence sufficient & Resolved decision & Opposite-decision witness \\"
"\midrule"];
cases = C.cases;
for i = 1:numel(cases)
    c = cases(i);
    if i > 1, L(end + 1) = "\addlinespace"; end %#ok<AGROW>
    L(end + 1) = sprintf("\\multicolumn{5}{@{}l}{\\textit{Prescribed %s; observed stress \\qty{%g}{MPa}}} \\\\", ...
        c.loading_convention, c.evidence.stress); %#ok<AGROW>
    for name = string(fieldnames(c.claims))'
        a = c.claims.(name);
        compat = string(a.compatible_explanations);
        if isempty(compat), compat = "none"; else, compat = strjoin(compat, ", "); end
        decision = string(a.decision);
        if isempty(a.decision), decision = string(a.status); end
        witness = "none";
        if ~isempty(a.opposite_decision_witness)
            witness = strjoin(string(a.opposite_decision_witness), " / ");
        end
        L(end + 1) = sprintf("\\quad %s & %s & %s & %s & %s \\\\", name, compat, ...
            yesno(a.sufficient), decision, witness); %#ok<AGROW>
    end
end
L = [L
"\bottomrule"
"\multicolumn{5}{@{}l}{\footnotesize Sufficient: every compatible explanation gives the same correctness decision.} \\"
"\end{tabular}"];
writelines(L, fullfile(csDir, 'decisions-table.tex'));
end
